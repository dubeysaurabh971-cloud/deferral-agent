def build_adversarial_set() -> list[dict]:
    records = []
    idx = 1
    for text, note in OUT_OF_KB:
        records.append({"item_id": f"A{idx:03d}", "category": "out_of_kb", "ticket_text": text,
                         "expected_decision": "ESCALATE", "injection_attempt": False, "note": note})
        idx += 1
    for text, note in AMBIGUOUS:
        records.append({"item_id": f"A{idx:03d}", "category": "ambiguous", "ticket_text": text,
                         "expected_decision": "CLARIFY", "injection_attempt": False, "note": note})
        idx += 1
    for text, decision, note in INJECTION:
        records.append({"item_id": f"A{idx:03d}", "category": "injection", "ticket_text": text,
                         "expected_decision": decision, "injection_attempt": True, "note": note})
        idx += 1
    for text, note in NEAR_MISS:
        records.append({"item_id": f"A{idx:03d}", "category": "near_miss", "ticket_text": text,
                         "expected_decision": "ESCALATE", "injection_attempt": False, "note": note})
        idx += 1
    return records


def write_adversarial_jsonl() -> None:
    config.DATA_DIR.joinpath("adversarial").mkdir(parents=True, exist_ok=True)
    path = config.DATA_DIR / "adversarial" / "adversarial_set.jsonl"
    records = build_adversarial_set()
    with path.open("w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r) + "\n")
    print(f"Wrote {len(records)} adversarial items to {path}")


if __name__ == "__main__":
    write_adversarial_jsonl()
